// Compiles every contract under contracts/ with solc-js and writes src/generated/artifacts.ts
// (gitignored; produced by the `generate` task).
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import solc from "solc";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contractsDir = join(root, "contracts");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : path.endsWith(".sol") ? [path] : [];
  });
}

const sources = {};
for (const file of walk(contractsDir)) {
  sources[relative(contractsDir, file).replaceAll("\\", "/")] = {
    content: readFileSync(file, "utf8"),
  };
}

const output = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: "Solidity",
      sources,
      settings: {
        optimizer: { enabled: true, runs: 200 },
        // paris: no PUSH0/MCOPY, so the bytecode runs on any EVM Celo has used.
        evmVersion: "paris",
        outputSelection: {
          "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] },
        },
      },
    }),
    {
      import: (path) => {
        try {
          return { contents: readFileSync(join(contractsDir, path), "utf8") };
        } catch {
          return { error: `not found: ${path}` };
        }
      },
    },
  ),
);

const errors = (output.errors ?? []).filter((e) => e.severity === "error");
for (const e of output.errors ?? [])
  console.error(e.severity.toUpperCase(), e.formattedMessage.trim());
if (errors.length > 0) process.exit(1);

const artifacts = {};
for (const [file, contracts] of Object.entries(output.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    if (!c.evm.bytecode.object) continue; // interfaces
    artifacts[name] = {
      source: file,
      abi: c.abi,
      bytecode: `0x${c.evm.bytecode.object}`,
      deployedBytecode: `0x${c.evm.deployedBytecode.object}`,
    };
  }
}

mkdirSync(join(root, "src", "generated"), { recursive: true });
writeFileSync(
  join(root, "src", "generated", "artifacts.ts"),
  `// GENERATED by scripts/compile.mjs. Do not edit.\nexport const artifacts = ${JSON.stringify(artifacts, null, 2)} as const;\n`,
);
console.log(
  Object.entries(artifacts)
    .map(([n, a]) => `${n} ${(a.deployedBytecode.length - 2) / 2}B`)
    .join(", "),
);
